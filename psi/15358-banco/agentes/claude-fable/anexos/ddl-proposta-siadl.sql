CREATE TABLE SDL_DISPOSITIVO_CLIENTE (
  NU_DISPOSITIVO             BIGINT        NOT NULL IDENTITY,
  NU_CLIENTE                 INT           NOT NULL,
  CO_TIPO_DISPOSITIVO        TINYINT       NOT NULL,
  NO_SISTEMA_OPERACIONAL     VARCHAR(30)   NOT NULL,
  CO_DISPOSITIVO             VARCHAR(128)  NOT NULL,           -- identificador técnico (dado sensível: DDM)
  DT_VINCULO                 DATE          NOT NULL,            -- era TIMESTAMP: corrigido
  IC_SITUACAO_DISPOSITIVO    BIT           NOT NULL CONSTRAINT DF_DISPOSITIVO_SIT DEFAULT 1,
  DH_INCLUSAO_REGISTRO       DATETIME2(3)  NOT NULL CONSTRAINT DF_DISPOSITIVO_INCL DEFAULT SYSDATETIME(),
  CONSTRAINT PK_SDL_DISPOSITIVO PRIMARY KEY CLUSTERED (NU_DISPOSITIVO),
  CONSTRAINT UQ_SDL_DISPOSITIVO_CO UNIQUE (CO_DISPOSITIVO),
  CONSTRAINT FK_SDL_DISPOSITIVO_CLIENTE FOREIGN KEY (NU_CLIENTE) REFERENCES SDL_CLIENTE (NU_CLIENTE)
) WITH (DATA_COMPRESSION = PAGE);

CREATE NONCLUSTERED INDEX IX_SDL_DISPOSITIVO_CLIENTE
  ON SDL_DISPOSITIVO_CLIENTE (NU_CLIENTE)
  INCLUDE (CO_TIPO_DISPOSITIVO, IC_SITUACAO_DISPOSITIVO, DT_VINCULO);

CREATE TABLE SDL_LIMITE_CONTA (
  NU_LIMITE_CONTA     BIGINT        NOT NULL IDENTITY,
  NU_CONTA            BIGINT        NOT NULL,
  CO_TIPO_LIMITE      TINYINT       NOT NULL,
  VR_LIMITE           DECIMAL(17,2) NOT NULL CONSTRAINT CK_SDL_LIMITE_VALOR CHECK (VR_LIMITE >= 0),
  DT_INICIO_VIGENCIA  DATE          NOT NULL,                  -- era TIMESTAMP: corrigido (application-time)
  DT_FIM_VIGENCIA     DATE          NULL,                      -- NULL = vigente
  VS_CONTROLE_CONCORRENCIA ROWVERSION,
  CONSTRAINT PK_SDL_LIMITE_CONTA PRIMARY KEY CLUSTERED (NU_LIMITE_CONTA),
  CONSTRAINT FK_SDL_LIMITE_CONTA FOREIGN KEY (NU_CONTA)       REFERENCES SDL_CONTA (NU_CONTA),
  CONSTRAINT FK_SDL_LIMITE_TIPO  FOREIGN KEY (CO_TIPO_LIMITE) REFERENCES SDL_TIPO_LIMITE (CO_TIPO_LIMITE),
  CONSTRAINT CK_SDL_LIMITE_VIGENCIA CHECK (DT_FIM_VIGENCIA IS NULL OR DT_FIM_VIGENCIA > DT_INICIO_VIGENCIA)
) WITH (DATA_COMPRESSION = PAGE);

-- Regra temporal aplicada no banco: no máximo UM limite vigente por conta+tipo
-- (a não sobreposição entre vigências históricas é garantida por validação
--  transacional na gravação + conciliação periódica — ver seção 4.5 da PT)
CREATE UNIQUE NONCLUSTERED INDEX IX_SDL_LIMITE_VIGENTE
  ON SDL_LIMITE_CONTA (NU_CONTA, CO_TIPO_LIMITE)
  WHERE DT_FIM_VIGENCIA IS NULL;

-- Auditoria sistêmica (system-time) complementar à vigência negocial (TE074 3.2.7)
ALTER TABLE SDL_LIMITE_CONTA ADD
  DH_INICIO_SISTEMA DATETIME2(7) GENERATED ALWAYS AS ROW START HIDDEN
      CONSTRAINT DF_LIMITE_SYSSTART DEFAULT SYSUTCDATETIME() NOT NULL,
  DH_FIM_SISTEMA    DATETIME2(7) GENERATED ALWAYS AS ROW END HIDDEN
      CONSTRAINT DF_LIMITE_SYSEND   DEFAULT CONVERT(DATETIME2(7),'9999-12-31 23:59:59.9999999') NOT NULL,
  PERIOD FOR SYSTEM_TIME (DH_INICIO_SISTEMA, DH_FIM_SISTEMA);

ALTER TABLE SDL_LIMITE_CONTA
  SET (SYSTEM_VERSIONING = ON (HISTORY_TABLE = dbo.SDL_LIMITE_CONTA_HISTORICO,
                               DATA_COMPRESSION = PAGE));


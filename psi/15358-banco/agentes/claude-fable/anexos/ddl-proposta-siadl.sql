-- Generalização PF×PJ implementada em tabela única (divergência nº 3, seção 5)
CREATE TABLE SDL_CLIENTE (
  NU_CLIENTE                 INT           NOT NULL IDENTITY,
  NO_CLIENTE                 VARCHAR(150)  NOT NULL,
  NU_CPF_CNPJ                BIGINT        NOT NULL,
  IC_TIPO_PESSOA             CHAR(1)       NOT NULL,           -- F = física / J = jurídica
  DT_NASCIMENTO              DATE          NULL,               -- específico PF
  CO_NATUREZA_JURIDICA       SMALLINT      NULL,               -- específico PJ
  DH_CADASTRO                DATETIME2(3)  NOT NULL,           -- era TIMESTAMP: corrigido
  CO_SITUACAO_CLIENTE        TINYINT       NOT NULL,
  CO_SEGMENTO_CLIENTE        TINYINT       NOT NULL,
  DH_INCLUSAO_REGISTRO       DATETIME2(3)  NOT NULL CONSTRAINT DF_CLIENTE_INCL DEFAULT SYSDATETIME(),
  DH_ALTERACAO_REGISTRO      DATETIME2(3)  NULL,
  CO_USUARIO_ULTIMA_ALTERACAO VARCHAR(30)  NULL,
  VS_CONTROLE_CONCORRENCIA   ROWVERSION,                        -- uso legítimo: optimistic locking
  CONSTRAINT PK_SDL_CLIENTE PRIMARY KEY CLUSTERED (NU_CLIENTE),
  CONSTRAINT UQ_SDL_CLIENTE_CPF_CNPJ UNIQUE (NU_CPF_CNPJ),
  CONSTRAINT FK_SDL_CLIENTE_SITUACAO FOREIGN KEY (CO_SITUACAO_CLIENTE) REFERENCES SDL_SITUACAO_CLIENTE (CO_SITUACAO_CLIENTE),
  CONSTRAINT FK_SDL_CLIENTE_SEGMENTO FOREIGN KEY (CO_SEGMENTO_CLIENTE) REFERENCES SDL_SEGMENTO_CLIENTE (CO_SEGMENTO_CLIENTE),
  CONSTRAINT CK_SDL_CLIENTE_TIPO CHECK (IC_TIPO_PESSOA IN ('F','J')),
  -- CHECKs condicionais da generalização exclusiva (salvaguarda da divergência nº 3)
  CONSTRAINT CK_SDL_CLIENTE_PF CHECK (IC_TIPO_PESSOA <> 'F' OR CO_NATUREZA_JURIDICA IS NULL),
  CONSTRAINT CK_SDL_CLIENTE_PJ CHECK (IC_TIPO_PESSOA <> 'J' OR DT_NASCIMENTO IS NULL)
) WITH (DATA_COMPRESSION = PAGE);

CREATE TABLE SDL_CONTA (
  NU_CONTA                   BIGINT        NOT NULL IDENTITY,
  NU_CLIENTE                 INT           NOT NULL,
  NU_CONTA_NEGOCIAL          VARCHAR(30)   NOT NULL,
  CO_TIPO_CONTA              TINYINT       NOT NULL,
  DT_ABERTURA                DATE          NOT NULL,            -- era TIMESTAMP: corrigido
  CO_SITUACAO_CONTA          TINYINT       NOT NULL,
  DH_INCLUSAO_REGISTRO       DATETIME2(3)  NOT NULL CONSTRAINT DF_CONTA_INCL DEFAULT SYSDATETIME(),
  DH_ALTERACAO_REGISTRO      DATETIME2(3)  NULL,
  CO_USUARIO_ULTIMA_ALTERACAO VARCHAR(30)  NULL,
  CONSTRAINT PK_SDL_CONTA PRIMARY KEY CLUSTERED (NU_CONTA),
  CONSTRAINT UQ_SDL_CONTA_NEGOCIAL UNIQUE (NU_CONTA_NEGOCIAL),
  CONSTRAINT FK_SDL_CONTA_CLIENTE  FOREIGN KEY (NU_CLIENTE)        REFERENCES SDL_CLIENTE (NU_CLIENTE),
  CONSTRAINT FK_SDL_CONTA_TIPO     FOREIGN KEY (CO_TIPO_CONTA)     REFERENCES SDL_TIPO_CONTA (CO_TIPO_CONTA),
  CONSTRAINT FK_SDL_CONTA_SITUACAO FOREIGN KEY (CO_SITUACAO_CONTA) REFERENCES SDL_SITUACAO_CONTA (CO_SITUACAO_CONTA)
) WITH (DATA_COMPRESSION = PAGE);

CREATE NONCLUSTERED INDEX IX_SDL_CONTA_CLIENTE
  ON SDL_CONTA (NU_CLIENTE) INCLUDE (NU_CONTA_NEGOCIAL, CO_TIPO_CONTA, CO_SITUACAO_CONTA);

--------------------------------------------------------------------------------
-- 4. TRANSACIONAIS MASSIVAS (particionadas, PK composta alinhada — Alternativa A)
--------------------------------------------------------------------------------
CREATE TABLE SDL_TRANSACAO (
  NU_TRANSACAO           BIGINT        NOT NULL IDENTITY,
  NU_CONTA               BIGINT        NOT NULL,
  NU_CANAL               TINYINT       NOT NULL,
  DH_TRANSACAO           DATETIME2(3)  NOT NULL,               -- era TIMESTAMP: corrigido
  VR_TRANSACAO           DECIMAL(17,2) NOT NULL,
  CO_TIPO_TRANSACAO      TINYINT       NOT NULL,
  CO_SITUACAO_TRANSACAO  TINYINT       NOT NULL,               -- estado corrente (trilha no histórico)
  NU_TRANSACAO_ORIGINAL  BIGINT        NULL,                   -- vínculo do estorno (seção 4.6, abordagem A)
  DH_INCLUSAO_REGISTRO   DATETIME2(3)  NOT NULL CONSTRAINT DF_TRANSACAO_INCL DEFAULT SYSDATETIME(),
  CONSTRAINT PK_SDL_TRANSACAO PRIMARY KEY CLUSTERED (DH_TRANSACAO, NU_TRANSACAO)
      ON PS_MENSAL (DH_TRANSACAO),
  CONSTRAINT FK_SDL_TRANSACAO_CONTA    FOREIGN KEY (NU_CONTA)              REFERENCES SDL_CONTA (NU_CONTA),
  CONSTRAINT FK_SDL_TRANSACAO_CANAL    FOREIGN KEY (NU_CANAL)              REFERENCES SDL_CANAL (NU_CANAL),
  CONSTRAINT FK_SDL_TRANSACAO_TIPO     FOREIGN KEY (CO_TIPO_TRANSACAO)     REFERENCES SDL_TIPO_TRANSACAO (CO_TIPO_TRANSACAO),
  CONSTRAINT FK_SDL_TRANSACAO_SITUACAO FOREIGN KEY (CO_SITUACAO_TRANSACAO) REFERENCES SDL_SITUACAO_TRANSACAO (CO_SITUACAO_TRANSACAO),
  CONSTRAINT CK_SDL_TRANSACAO_VALOR CHECK (VR_TRANSACAO > 0)   -- mantido: estorno é evento próprio
) WITH (DATA_COMPRESSION = ROW  ON PARTITIONS (12 TO 14),      -- quentes (últimos 3 meses)
        DATA_COMPRESSION = PAGE ON PARTITIONS (1 TO 11));      -- mornas/frias

-- Identificador negocial único (apoio às FKs lógicas e consultas por id)
CREATE UNIQUE NONCLUSTERED INDEX UX_SDL_TRANSACAO_NU
  ON SDL_TRANSACAO (NU_TRANSACAO, DH_TRANSACAO)
  ON PS_MENSAL (DH_TRANSACAO);

-- Extrato por conta e período (consulta crítica nº 1)
CREATE NONCLUSTERED INDEX IX_SDL_TRANSACAO_CONTA_DATA
  ON SDL_TRANSACAO (NU_CONTA, DH_TRANSACAO DESC)
  INCLUDE (VR_TRANSACAO, CO_TIPO_TRANSACAO, CO_SITUACAO_TRANSACAO)
  ON PS_MENSAL (DH_TRANSACAO);

CREATE TABLE SDL_TRANSACAO_HISTORICO (
  NU_TRANSACAO_HISTORICO BIGINT        NOT NULL IDENTITY,
  NU_TRANSACAO           BIGINT        NOT NULL,
  DH_EVENTO              DATETIME2(3)  NOT NULL,               -- era TIMESTAMP: corrigido
  CO_SITUACAO_ANTERIOR   TINYINT       NULL,
  CO_SITUACAO_NOVA       TINYINT       NOT NULL,
  CO_ORIGEM_EVENTO       TINYINT       NOT NULL,
  CONSTRAINT PK_SDL_TRANSACAO_HISTORICO
      PRIMARY KEY CLUSTERED (DH_EVENTO, NU_TRANSACAO_HISTORICO) ON PS_MENSAL (DH_EVENTO),
  CONSTRAINT FK_SDL_TRH_ORIGEM FOREIGN KEY (CO_ORIGEM_EVENTO) REFERENCES SDL_ORIGEM_EVENTO (CO_ORIGEM_EVENTO)
) WITH (DATA_COMPRESSION = PAGE);                              -- append-only: PAGE integral

-- Trilha de uma transação (consulta crítica nº 5)
CREATE NONCLUSTERED INDEX IX_SDL_TRH_TRANSACAO
  ON SDL_TRANSACAO_HISTORICO (NU_TRANSACAO, DH_EVENTO)
  INCLUDE (CO_SITUACAO_ANTERIOR, CO_SITUACAO_NOVA, CO_ORIGEM_EVENTO)
  ON PS_MENSAL (DH_EVENTO);

CREATE TABLE SDL_ATENDIMENTO (
  NU_ATENDIMENTO          BIGINT        NOT NULL IDENTITY,
  NU_CLIENTE              INT           NOT NULL,
  NU_CANAL                TINYINT       NOT NULL,             -- era VARCHAR(30) livre: agora FK de domínio
  DH_ABERTURA             DATETIME2(3)  NOT NULL,             -- era TIMESTAMP: corrigido
  DH_FECHAMENTO           DATETIME2(3)  NULL,
  CO_SITUACAO_ATENDIMENTO TINYINT       NOT NULL,
  CO_PRIORIDADE           TINYINT       NOT NULL,
  DH_INCLUSAO_REGISTRO    DATETIME2(3)  NOT NULL CONSTRAINT DF_ATENDIMENTO_INCL DEFAULT SYSDATETIME(),
  CONSTRAINT PK_SDL_ATENDIMENTO PRIMARY KEY CLUSTERED (DH_ABERTURA, NU_ATENDIMENTO)
      ON PS_MENSAL (DH_ABERTURA),
  CONSTRAINT FK_SDL_ATENDIMENTO_CLIENTE    FOREIGN KEY (NU_CLIENTE)              REFERENCES SDL_CLIENTE (NU_CLIENTE),
  CONSTRAINT FK_SDL_ATENDIMENTO_CANAL      FOREIGN KEY (NU_CANAL)                REFERENCES SDL_CANAL (NU_CANAL),
  CONSTRAINT FK_SDL_ATENDIMENTO_SITUACAO   FOREIGN KEY (CO_SITUACAO_ATENDIMENTO) REFERENCES SDL_SITUACAO_ATENDIMENTO (CO_SITUACAO_ATENDIMENTO),
  CONSTRAINT FK_SDL_ATENDIMENTO_PRIORIDADE FOREIGN KEY (CO_PRIORIDADE)           REFERENCES SDL_PRIORIDADE (CO_PRIORIDADE)
) WITH (DATA_COMPRESSION = PAGE);

-- Histórico de atendimentos por cliente e período (consulta crítica nº 2)
CREATE NONCLUSTERED INDEX IX_SDL_ATENDIMENTO_CLIENTE_DATA
  ON SDL_ATENDIMENTO (NU_CLIENTE, DH_ABERTURA DESC)
  INCLUDE (NU_CANAL, CO_SITUACAO_ATENDIMENTO, CO_PRIORIDADE, DH_FECHAMENTO)
  ON PS_MENSAL (DH_ABERTURA);

-- Índice FILTRADO: fila operacional de atendimentos em aberto (consulta crítica nº 3)
CREATE NONCLUSTERED INDEX IX_SDL_ATENDIMENTO_ABERTOS
  ON SDL_ATENDIMENTO (CO_SITUACAO_ATENDIMENTO, DH_ABERTURA)
  INCLUDE (NU_ATENDIMENTO, NU_CLIENTE, NU_CANAL, CO_PRIORIDADE)
  WHERE DH_FECHAMENTO IS NULL;

CREATE TABLE SDL_INTERACAO_ATENDIMENTO (
  NU_INTERACAO            BIGINT        NOT NULL IDENTITY,
  NU_ATENDIMENTO          BIGINT        NOT NULL,
  CO_TIPO_INTERACAO       TINYINT       NOT NULL,
  DH_INTERACAO            DATETIME2(3)  NOT NULL,              -- era TIMESTAMP: corrigido
  CO_ORIGEM_EVENTO        TINYINT       NOT NULL,
  DE_CONTEUDO_RESUMIDO    VARCHAR(500)  NULL,
  CONSTRAINT PK_SDL_INTERACAO PRIMARY KEY CLUSTERED (DH_INTERACAO, NU_INTERACAO)
      ON PS_MENSAL (DH_INTERACAO),
  CONSTRAINT FK_SDL_INTERACAO_TIPO   FOREIGN KEY (CO_TIPO_INTERACAO) REFERENCES SDL_TIPO_INTERACAO (CO_TIPO_INTERACAO),
  CONSTRAINT FK_SDL_INTERACAO_ORIGEM FOREIGN KEY (CO_ORIGEM_EVENTO)  REFERENCES SDL_ORIGEM_EVENTO (CO_ORIGEM_EVENTO)
) WITH (DATA_COMPRESSION = PAGE);

-- Interações de um atendimento em ordem cronológica
CREATE NONCLUSTERED INDEX IX_SDL_INTERACAO_ATENDIMENTO
  ON SDL_INTERACAO_ATENDIMENTO (NU_ATENDIMENTO, DH_INTERACAO)
  INCLUDE (CO_TIPO_INTERACAO, CO_ORIGEM_EVENTO)
  ON PS_MENSAL (DH_INTERACAO);


CREATE TABLE SDL_SITUACAO_ATENDIMENTO (CO_SITUACAO_ATENDIMENTO TINYINT NOT NULL CONSTRAINT PK_SDL_SIT_ATEND       PRIMARY KEY, NO_SITUACAO_ATENDIMENTO VARCHAR(30) NOT NULL);
